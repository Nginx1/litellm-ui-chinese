ATTR_PATTERNS = [
    (re.compile(r'((?<![\w$])children:)"((?:[^"\\]|\\.){2,120})"'), 'children'),
    (re.compile(r'((?<![\w$])label:)"((?:[^"\\]|\\.){2,120})"'), 'label'),
    (re.compile(r'((?<![\w$])title:)"((?:[^"\\]|\\.){2,120})"'), 'title'),
    (re.compile(r'((?<![\w$])placeholder:)"((?:[^"\\]|\\.){2,120})"'), 'placeholder'),
    (re.compile(r'((?<![\w$])description:)"((?:[^"\\]|\\.){2,120})"'), 'description'),
    (re.compile(r'((?<![\w$])message:)"((?:[^"\\]|\\.){2,120})"'), 'message'),
    (re.compile(r'((?<![\w$])heading:)"((?:[^"\\]|\\.){2,120})"'), 'heading'),
]

changed_files = 0
total_replacements = 0
report = {}

for root, dirs, files in os.walk(UI):
    for fn in files:
        if not (fn.endswith(".js") or fn.endswith(".html")):
            continue
        path = os.path.join(root, fn)
        try:
            with open(path, encoding="utf-8", errors="ignore") as f:
                content = f.read()
        except Exception:
            continue
        orig = content
        file_count = 0
        counter = [0]
        def repl(m):
            t = DICT.get(m.group(2).strip())
            if t is None:
                return m.group(0)
            global total_replacements
            total_replacements += 1
            counter[0] += 1
            return m.group(1) + '"' + t + '"'
        for pat, attr in ATTR_PATTERNS:
            counter[0] = 0
            content = pat.sub(repl, content)
            file_count += counter[0]
        if content != orig:
            bak = path + ".en.bak"
            if not os.path.exists(bak):
                shutil.copy2(path, bak)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            changed_files += 1
            report[path] = file_count

print(f"v8 全量汉化: 修改 {changed_files} 个文件, 共 {total_replacements} 处替换")
print("\n=== 修改文件 TOP20 ===")
for p, c in sorted(report.items(), key=lambda x: -x[1])[:20]:
    print(f"  {c:4d} 处  {os.path.basename(p)}")
